#!/usr/bin/env python3
# ---------------------------------------------------------------------
# gen_splash_logo.py - generate the boot-splash wordmark as a 2-bit mask
#
# The stock microByte firmware renders "micro" / "BYTE" at runtime with
# FreeType out of Ubuntu-R.ttf (components/boot_screen/, 12 MB of source
# tree dragged in just for two words). retro-go already links two CJK
# pixel fonts, so instead we bake the wordmark here, at build-authoring
# time, into a plain 2-bit grey bitmap: ~0.9 KB of flash and zero runtime
# font machinery.
#
# 2 bits because the stock renderer keeps FreeType's 2-bit grey coverage
# (draw_gray2_bitmap in boot_screen.c:286) and blends white over the
# plasma at 0 / 50 / 75 / 100%. A 1-bit cut-out would look jagged at 30px.
#
# Placement reproduces the stock renderer's maths (see
# font_render.c:34-35 and boot_screen.c:255-260):
#
#     max_pixel_height = 30 * (yMax - yMin) / units_per_EM + 1
#     origin           = 30 * (-yMin)       / units_per_EM
#     ink_top_in_box   = max_pixel_height - origin - bitmap_top
#
# so the text box occupies y = 100..100+max_pixel_height and the
# baseline sits at 100 + (max_pixel_height - origin) = 100 + ascender.
#
# Usage:
#   python tools/gen_splash_logo.py <Ubuntu-R.ttf> [output.h]
#
# The wordmark is rasterized from Ubuntu-R.ttf (Ubuntu Font Licence 1.0),
# which is the font stock microByte used at runtime via FreeType. Pass the
# path to your own copy - no font file is shipped in this repo.
# ---------------------------------------------------------------------
import sys, os
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

if len(sys.argv) < 2:
    sys.exit(__doc__ or "usage: gen_splash_logo.py <Ubuntu-R.ttf> [output.h]")

TTF    = sys.argv[1]
OUT    = sys.argv[2] if len(sys.argv) > 2 else \
    os.path.join(os.path.dirname(os.path.abspath(__file__)),
                 "..", "components", "retro-go", "bitmaps", "image_splash_text.h")

SIZE       = 30      # pixel em size, matches font_render_init(..., 30, 48)
BOX_Y      = 100     # stock src_y for both words
WORD_L     = "micro"
WORD_R     = "BYTE"
WORD_X_L   = 50      # stock src_x
WORD_X_R   = 130     # stock src_x
SCREEN_W   = 240
SCREEN_H   = 240

# Coverage -> 2-bit grey level. FreeType's 2-bit mode emits exactly
# 0/85/170/255, so these cut points reproduce it losslessly.
GREY_CUTS  = (64, 128, 192)   # level = 0 if a < 64, 1 if < 128, 2 if < 192, else 3

# --- work out the stock renderer's ascender ---------------------------
ft = TTFont(TTF, fontNumber=0, lazy=True)
head = ft["head"]
upem, ymin, ymax = head.unitsPerEm, head.yMin, head.yMax
max_pixel_height = (SIZE * (ymax - ymin)) // upem + 1
origin           = (SIZE * (-ymin)) // upem
ascender         = max_pixel_height - origin
baseline         = BOX_Y + ascender
print(f"{os.path.basename(TTF)}: upem={upem} yMin={ymin} yMax={ymax}")
print(f"  max_pixel_height={max_pixel_height} origin={origin} "
      f"ascender={ascender} baseline_y={baseline}")

# --- render both words on a common baseline --------------------------
font = ImageFont.truetype(TTF, SIZE)
img = Image.new("L", (SCREEN_W, SCREEN_H), 0)
draw = ImageDraw.Draw(img)
draw.text((WORD_X_L, baseline), WORD_L, font=font, fill=255, anchor="ls")
draw.text((WORD_X_R, baseline), WORD_R, font=font, fill=255, anchor="ls")

bbox = img.getbbox()
if bbox is None:
    sys.exit("nothing rendered - wrong font?")
left, top, right, bottom = bbox
w, h = right - left, bottom - top
print(f"  ink bbox = ({left},{top})-({right},{bottom})  ->  {w}x{h} at ({left},{top})")

# --- pack: row-major, 4 pixels/byte, each row padded to a whole byte,
#     most significant pixel first (i.e. pixel 0 sits in bits 7..6) ----
def grey_level(a):
    for i, cut in enumerate(GREY_CUTS):
        if a < cut:
            return i
    return 3

row_bytes = (w * 2 + 7) // 8
px = img.load()
rows = []
levels = {}
for y in range(top, bottom):
    row = bytearray(row_bytes)
    for x in range(left, right):
        lv = grey_level(px[x, y])
        levels[lv] = levels.get(lv, 0) + 1
        c = x - left
        row[c >> 2] |= lv << (6 - ((c & 3) << 1))
    rows.append(bytes(row))
data = b"".join(rows)

with open(OUT, "w", newline="\n") as f:
    f.write(f"""// Generated by tools/gen_splash_logo.py - do not edit by hand.
// Source: {os.path.basename(TTF)} at {SIZE}px, baseline y={baseline}
//         (matches the stock microByte boot screen's FreeType placement).
// {w}x{h} 2-bit grey mask, row-major, 4 pixels per byte, each row padded to a
// whole byte, most significant pixel first. Levels are the same 0/1/2/3 the
// stock draw_gray2_bitmap() blends white with (0% / 50% / 75% / 100%).
// The whole thing is ~{len(data)} bytes.
#pragma once
#include <stdint.h>

#define SPLASH_TEXT_X      {left}
#define SPLASH_TEXT_Y      {top}
#define SPLASH_TEXT_W      {w}
#define SPLASH_TEXT_H      {h}
#define SPLASH_TEXT_STRIDE {row_bytes}

static const uint8_t splash_text_mask[] = {{
""")
    for i in range(0, len(data), 16):
        f.write("    " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]) + "\n")
    f.write("};\n")

print(f"  grey histogram (level: pixels) = "
      + ", ".join(f"{k}:{v}" for k, v in sorted(levels.items())))
print(f"wrote {os.path.relpath(OUT)}: {w}x{h}, {len(data)} bytes ({row_bytes}/row)")
